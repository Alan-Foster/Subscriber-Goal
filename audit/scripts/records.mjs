// Renders audit records as AI-ready Markdown that follows audit/issue-template.md.
const notYet = "_Not yet investigated._";

const text = (value) => {
  if (value === undefined || value === null || value === "") return notYet;
  if (Array.isArray(value)) {
    return value.length === 0
      ? notYet
      : value.map((item) => `- ${item}`).join("\n");
  }
  return String(value);
};

const typeLabels = {
  problem: "Problem",
  test_gap: "Test gap",
  log_gap: "Log gap",
};

/** Markdown for one record, using the issue template's section headings. */
export function renderRecord(record) {
  const confidence = record.type === "problem" ? ` · ${record.confidence}` : "";
  const loc = record.estimatedLoc
    ? `About ${record.estimatedLoc.code} lines of code and ${record.estimatedLoc.tests} lines of tests.`
    : "Estimated lines of code: _not yet estimated._";
  return [
    `# ${record.id}: ${record.title}`,
    "",
    `**${typeLabels[record.type] ?? record.type}${confidence}** · criticality ${record.criticality?.score ?? "?"}/10 · areas ${(record.areas ?? []).join(", ")}${record.paths?.length ? ` · paths ${record.paths.join(", ")}` : ""}`,
    "",
    "> Audit record. Generated from `audit/records/" +
      `${record.id}.json` +
      "` by `npm run audit:records`; edit the JSON, not this file. To turn it into an issue, follow `audit/issue-template.md`.",
    "",
    "## 1. Current Implementation",
    "",
    text(record.current),
    "",
    "## 2. Problem and evidence",
    "",
    text(record.evidence),
    "",
    `**Location:** ${text(record.location)}`,
    "",
    `**Observed outcome:** ${text(record.outcome)}`,
    "",
    "**Unverified assumptions:**",
    "",
    text(record.assumptions),
    "",
    "## 3. Required behavior and scope",
    "",
    text(record.required),
    "",
    "## 4. Relevant Documentation",
    "",
    text(record.docs),
    "",
    "## 5. Implementation map and blockers",
    "",
    `**Reuse:** ${text(record.reuse)}`,
    "",
    `**Blockers and open decisions:** ${text(record.blockers)}`,
    "",
    "**Still to investigate:**",
    "",
    text(record.investigate),
    "",
    "## 6. Edge cases and regression risks",
    "",
    text(record.edgeCases),
    "",
    "## 7. Tests and verification",
    "",
    text(record.tests),
    "",
    "## 8. Acceptance criteria",
    "",
    "_Written when this record becomes an issue._",
    "",
    "## 9. Criticality and Implementation Cost",
    "",
    `**${record.criticality?.score ?? "?"}/10.** ${record.criticality?.why ?? notYet}`,
    "",
    loc,
    "",
    "## Related",
    "",
    text(record.related),
    "",
  ].join("\n");
}

/** Markdown index of all records, most critical first. */
export function renderRecordIndex(records) {
  const sorted = [...records].sort(
    (a, b) =>
      (b.criticality?.score ?? 0) - (a.criticality?.score ?? 0) ||
      a.id.localeCompare(b.id),
  );
  return [
    "# Audit records",
    "",
    "Generated by `npm run audit:records`. Most critical first.",
    "",
    "| Record | Type | Criticality | Title |",
    "|---|---|---:|---|",
    ...sorted.map(
      (r) =>
        `| [${r.id}](${r.id}.md) | ${r.type}${r.type === "problem" ? ` (${r.confidence})` : ""} | ${r.criticality?.score ?? "?"} | ${String(r.title).replaceAll("|", "\\|")} |`,
    ),
    "",
  ].join("\n");
}
